"""Build index.html from timing.json: scene slots, narration track and burned-in captions.

Run after scripts/tts.py. Scene files must exist at compositions/<scene-id>.html.
"""
import html, json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
timing = json.load(open(os.path.join(ROOT, "timing.json"), encoding="utf-8"))
total = timing["total"]

narr = {s["id"]: {"dur": s["duration"], "L": [l["start"] for l in s["lines"]],
                 "E": [round(l["start"] + l["duration"], 3) for l in s["lines"]]} for s in timing["scenes"]}
open(os.path.join(ROOT, "assets", "timing.js"), "w", encoding="utf-8").write(
    "// Generated by scripts/build_index.py — scene-local narration line starts (L) and ends (E).\n"
    "window.__NARR = " + json.dumps(narr, ensure_ascii=False) + ";\n")

# Music bed: trim the generated track to the film, fade in 1.5s and out over the last 3s.
bgm_src = os.path.join(ROOT, "assets", "bgm", "bgm.mp3")
if os.path.exists(bgm_src):
    subprocess.check_call(["ffmpeg", "-v", "error", "-y", "-i", bgm_src, "-t", f"{total:.3f}",
                           "-af", f"afade=t=in:d=1.5,afade=t=out:st={total - 3:.3f}:d=3", "-b:a", "192k",
                           os.path.join(ROOT, "assets", "bgm", "bed.mp3")])

slots, captions = [], []
for s in timing["scenes"]:
    sid = s["id"]
    slots.append(
        f'      <div id="el-{sid}" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html"\n'
        f'        data-start="{s["start"]}" data-duration="{s["duration"]}" data-track-index="1"\n'
        f'        data-width="1920" data-height="1080"></div>'
    )
    lines = s["lines"]
    for i, ln in enumerate(lines):
        start = s["start"] + ln["start"]
        end = s["start"] + (lines[i + 1]["start"] if i + 1 < len(lines) else ln["start"] + ln["duration"] + 0.3)
        captions.append(
            f'        <div id="cap-{ln["id"]}" class="clip cap" data-start="{start:.3f}" data-duration="{end - start:.3f}"'
            f' data-track-index="1"><span>{html.escape(ln["text"])}</span></div>'
        )

FONT = """        @font-face {{ font-family: "Pretendard"; src: url("assets/fonts/Pretendard-SemiBold.woff2") format("woff2"); font-weight: 600; }}"""

cap_doc = f"""<!doctype html>
<html lang="ko">
  <head>
    <meta charset="UTF-8" />
    <!-- Generated by scripts/build_index.py from timing.json — edit the script, not this file. -->
  </head>
  <body>
    <template id="captions-template">
      <style>
{FONT.replace("{{", "{").replace("}}", "}")}
        #root {{ position: absolute; inset: 0; pointer-events: none; }}
        .cap {{ position: absolute; left: 0; right: 0; bottom: 56px; display: flex; justify-content: center; }}
        .cap span {{
          display: block; max-width: 1560px; padding: 14px 34px; border-radius: 14px;
          background: rgba(20, 22, 26, 0.8); color: #fff; text-align: center;
          font-family: "Pretendard", sans-serif; font-size: 42px; font-weight: 600; line-height: 1.38;
          letter-spacing: -0.01em; word-break: keep-all;
        }}
      </style>
      <div id="root" data-composition-id="captions" data-width="1920" data-height="1080">
{chr(10).join(captions)}
      </div>
      <script>
        window.__timelines["captions"] = gsap.timeline({{ paused: true }});
      </script>
    </template>
  </body>
</html>
"""
open(os.path.join(ROOT, "compositions", "captions.html"), "w", encoding="utf-8").write(cap_doc)

doc = f"""<!doctype html>
<html lang="ko">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <!-- Generated by scripts/build_index.py from timing.json — edit the script, not this file. -->
    <script src="assets/vendor/gsap.min.js"></script>
    <script src="assets/timing.js"></script>
    <link rel="stylesheet" href="assets/shared.css" />
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; overflow: hidden; background: #f7f4ee; }}
      #root {{ position: relative; width: 100%; height: 100%; overflow: hidden; background: var(--bg); }}
      #root > div[data-composition-src] {{ position: absolute; inset: 0; }}
      #el-captions {{ z-index: 50; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{total}" data-width="1920" data-height="1080">
{chr(10).join(slots)}

      <div id="el-captions" data-composition-id="captions" data-composition-src="compositions/captions.html"
        data-start="0" data-duration="{total}" data-track-index="3" data-track-kind="captions" data-width="1920" data-height="1080"></div>

      <audio id="narration" src="assets/narration.wav" data-start="0" data-duration="{total}" data-track-index="10" data-volume="1"></audio>
      <audio id="bgm" src="assets/bgm/bed.mp3" data-start="0" data-duration="{total}" data-track-index="11" data-volume="0.18"></audio>
    </div>
    <script>
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(doc)
print("index.html:", len(timing["scenes"]), "scenes,", len(captions), "captions,", total, "s")
